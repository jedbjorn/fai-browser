#!/usr/bin/env node
// Refreshes the embedded Public Suffix List used for domain roots ("https://*.example.com", src/origins.js).
//
//   node scripts/update-psl.mjs            # download https://publicsuffix.org/list/public_suffix_list.dat
//   node scripts/update-psl.mjs --file F   # use a local copy (default for offline: vendor/public_suffix_list.dat)
//
// Writes vendor/public_suffix_list.dat (the list as downloaded), src/psl-data.js (an ES module for the daemon, MCP and
// SDK) and extension/psl-data.js (a classic script the service worker loads with importScripts and the popup imports
// for its side effect: globalThis.FAI_PSL_RULES). Both carry the same rule string: every rule of the ICANN and PRIVATE
// sections, wildcard ("*.ck") and exception ("!www.ck") rules included, lower case, IDN labels in punycode, sorted.
// test/origins.test.js checks that the two generated files agree with each other and with the vendored list. Nothing
// fetches the list at run time.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { domainToASCII } from 'node:url';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
export const VENDORED = join(ROOT, 'vendor', 'public_suffix_list.dat');

/** The rules of a list file as `{ rules: string[], version }`: punycode, lower case, sorted, unique. */
export function parsePsl(text) {
  const rules = new Set();
  let sections = 0;
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (/^\/\/ ===BEGIN (ICANN|PRIVATE) DOMAINS===/.test(line)) sections++;
    if (!line || line.startsWith('//')) continue;
    const rule = line.split(/\s+/)[0].toLowerCase();
    const prefix = rule.startsWith('!') ? '!' : rule.startsWith('*.') ? '*.' : '';
    const name = rule.slice(prefix.length);
    const ascii = name.split('.').map(label => (/^[\x21-\x7e]+$/.test(label) ? label : domainToASCII(label))).join('.');
    if (!/^[a-z0-9-]+(\.[a-z0-9-]+)*$/.test(ascii)) throw new Error(`Unexpected rule: ${rule}`);
    rules.add(prefix + ascii);
  }
  if (sections !== 2) throw new Error('Expected the ICANN and PRIVATE sections');
  if (rules.size < 5000) throw new Error(`Only ${rules.size} rules: not the full list`);
  const version = /\/\/ VERSION: (\S+)/.exec(text)?.[1] ?? 'unknown';
  return { rules: [...rules].sort(), version };
}

export function renderModule({ rules, version }) {
  return `// Generated by scripts/update-psl.mjs from the Public Suffix List (https://publicsuffix.org/list/, MPL-2.0),
// version ${version}. Do not edit; rerun the script. Rules: punycode, lower case, sorted, newline-separated.
export const PSL_VERSION = ${JSON.stringify(version)};
export const PSL_RULES = ${JSON.stringify(rules.join('\n'))};
`;
}

export function renderScript({ rules, version }) {
  return `// Generated by scripts/update-psl.mjs from the Public Suffix List (https://publicsuffix.org/list/, MPL-2.0),
// version ${version}. Do not edit; rerun the script. A classic script: the service worker loads it with importScripts
// and the popup imports it for its side effect. Rules: punycode, lower case, sorted, newline-separated.
globalThis.FAI_PSL_VERSION = ${JSON.stringify(version)};
globalThis.FAI_PSL_RULES = ${JSON.stringify(rules.join('\n'))};
`;
}

async function main(argv) {
  const at = argv.indexOf('--file');
  let text;
  if (at >= 0) {
    text = await readFile(argv[at + 1], 'utf8');
  } else {
    const response = await fetch(SOURCE);
    if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
    text = await response.text();
  }
  const parsed = parsePsl(text);
  await mkdir(dirname(VENDORED), { recursive: true });
  await writeFile(VENDORED, text);
  await writeFile(join(ROOT, 'src', 'psl-data.js'), renderModule(parsed));
  await writeFile(join(ROOT, 'extension', 'psl-data.js'), renderScript(parsed));
  console.log(`Public Suffix List ${parsed.version}: ${parsed.rules.length} rules`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => {
    console.error(error.message);
    process.exit(1);
  });
}
