// Origin entries of a tab request: exact origins ("https://app.example.com", matched exactly as before) and domain roots
// ("https://*.example.com": the registrable domain example.com and every subdomain of it, over https on the default
// port only). One matcher for every origin check: the lease, every observed page, `cross_origin`, link admission,
// `allowedUrls`, consent redirects and site-profile attachment.
//
// A domain root is written as a wildcard origin so it can never be mistaken for an exact one: before roots existed the
// daemon accepted "https://*.example.com" as an "exact" origin no tab could ever have, so no working request widens.
// The root must be a registrable domain (or a subdomain of one) under the Public Suffix List, embedded as generated data
// (scripts/update-psl.mjs; no run-time fetch): a bare TLD, "*.co.uk", a private suffix such as "*.github.io", a host
// under a TLD the list does not know ("*.foo.localhost") and a small fail-closed overlay of multi-tenant domains the
// list does not fully cover ("*.amazonaws.com", "*.azure.com", ...) are refused (docs/REFERENCE.md, "Domain roots").
import { PSL_RULES } from './psl-data.js';

// <site-match> Identical in src/origins.js, extension/permissions.js and extension/background.js (drift check in
// test/origins.test.js). Plain declarations only: the worker loads it as a classic script under the test harness.

// The Public Suffix List (ICANN and PRIVATE sections, wildcard and exception rules), vendored and generated by
// scripts/update-psl.mjs: PSL_RULES is defined just above this block in each file (src/psl-data.js here,
// extension/psl-data.js in the extension). Parsed once, on first use.
let SITE_PSL = null;
let SITE_PSL_PARENTS = null;
function pslRules() {
  if (!SITE_PSL) SITE_PSL = new Set(String(PSL_RULES || '').split('\n').filter(Boolean));
  return SITE_PSL;
}

// Every name with a public suffix strictly below it (amazonaws.com above s3.amazonaws.com, kawasaki.jp above the
// wildcard *.kawasaki.jp, r.appspot.com above *.r.appspot.com): a root there would span several owners.
function pslParents() {
  if (!SITE_PSL_PARENTS) {
    SITE_PSL_PARENTS = new Set();
    for (const rule of pslRules()) {
      const labels = rule.replace(/^[!]/, '').split('.');
      const own = rule.startsWith('*.') ? 1 : 0;
      for (let i = own + 1; i < labels.length; i++) SITE_PSL_PARENTS.add(labels.slice(i).join('.'));
      if (own) SITE_PSL_PARENTS.add(labels.slice(1).join('.'));
    }
  }
  return SITE_PSL_PARENTS;
}

// Fail-closed overlay for multi-tenant domains the list does not (fully) cover: no root at or under them, so a page
// there is only ever approved by its exact origin and never suggested as a root. `SITE_SHARED_LABELS`: a registrable
// domain whose first label is one of these (blogspot.de, blogspot.co.uk, ...).
const SITE_SHARED = new Set(['amazonaws.com', 'on.aws', 'azure.com', 'windows.net', 'azurecontainerapps.io',
  'github.dev', 'gitpod.io', 'googleusercontent.com', 'wordpress.com', 'glitch.me', 'firebaseio.com', 'neocities.org',
  'loca.lt', 'stackblitz.io', 'sourceforge.io', 'tumblr.com', 'substack.com', 'weebly.com', '000webhostapp.com',
  'codesandbox.io']);
const SITE_SHARED_LABELS = new Set(['blogspot']);

/**
 * The number of labels of `labels`' public suffix under the list's rules (the longest matching rule, an exception rule
 * winning; "*" by default), or 0 when the top-level label is not in the list at all (localhost, test, example, ...).
 */
function publicSuffixLength(labels) {
  const rules = pslRules();
  const n = labels.length;
  if (!rules.has(labels[n - 1]) && !rules.has(`*.${labels[n - 1]}`)) return 0;
  let best = 1;
  for (let i = n - 1; i >= 0; i--) {
    const name = labels.slice(i).join('.');
    if (rules.has(`!${name}`)) return n - i - 1;
    if (rules.has(name)) best = Math.max(best, n - i);
    if (i < n - 1 && rules.has(`*.${labels.slice(i + 1).join('.')}`)) best = Math.max(best, n - i);
  }
  return best;
}

/**
 * True for a host that can never be a domain root: a public suffix (or a name inside one, such as a wildcard rule's
 * label), a host under an unknown top-level label, or a shared hosting domain of the overlay.
 */
function isSiteSuffix(host) {
  const labels = host.split('.');
  const suffix = publicSuffixLength(labels);
  if (suffix === 0 || labels.length <= suffix || pslParents().has(host)) return true;
  for (const shared of SITE_SHARED) if (host === shared || host.endsWith(`.${shared}`)) return true;
  return SITE_SHARED_LABELS.has(labels[labels.length - suffix - 1]);
}

/**
 * The root of a domain-root entry "https://*.<root>": a lower-case ASCII (punycode) DNS name of at least two labels
 * ending in a letter label (no IP address), not a public suffix. Null for anything else, an exact origin included.
 */
function siteRoot(entry) {
  if (typeof entry !== 'string' || entry.length > 262) return null;
  const match = /^https:\/\/\*\.((?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z](?:[a-z0-9-]{0,61}[a-z0-9])?)$/.exec(entry);
  if (!match || match[1].length > 253 || isSiteSuffix(match[1])) return null;
  return match[1];
}

/** True when `host` is `root` itself or a subdomain of it. */
function hostInSite(host, root) {
  return typeof host === 'string' && (host === root || (host.length > root.length && host.endsWith(`.${root}`)));
}

/** The host of a default-port https origin ("https://docs.example.com"), else null. */
function siteHost(origin) {
  const match = typeof origin === 'string' ? /^https:\/\/([a-z0-9.-]+)$/.exec(origin) : null;
  return match && !match[1].endsWith('.') ? match[1] : null;
}

/**
 * True when `origin` (a tab's or page's origin, as URL.origin writes it) is covered by `entries`: equal to an exact
 * entry, or an https origin on the default port whose host is a domain root or one of its subdomains.
 */
function originCovered(origin, entries) {
  if (typeof origin !== 'string' || origin.includes('*') || !Array.isArray(entries)) return false;
  if (entries.includes(origin)) return true;
  const host = siteHost(origin);
  return Boolean(host) && entries.some(entry => {
    const root = siteRoot(entry);
    return root !== null && hostInSite(host, root);
  });
}

/** The Chrome host permission pattern for a domain root: "https://*.<root>/*" (the root and every subdomain). */
function sitePattern(root) {
  return `https://*.${root}/*`;
}
// </site-match>

/** True for a domain-root entry ("https://*.example.com" with a registrable root). */
export function isSiteEntry(entry) {
  return siteRoot(entry) !== null;
}

/**
 * An exact http(s) origin, or null: `value` must already be the origin itself (scheme, host, port; no path, query,
 * trailing slash, user info or wildcard), so what the host wrote is what is compared.
 */
export function exactOrigin(value) {
  if (typeof value !== 'string' || !value || value.length > 300 || value.includes('*')) return null;
  try {
    const url = new URL(value);
    if (url.protocol !== 'http:' && url.protocol !== 'https:') return null;
    if (url.username || url.password) return null;
    return url.origin === value ? value : null;
  } catch {
    return null;
  }
}

/**
 * Validates one `origins` entry. Returns `{ entry, root? }` for an exact origin or a domain root, or `{ error }` with
 * plain words for the host.
 */
export function checkOriginEntry(value) {
  const text = String(value ?? '').slice(0, 100);
  if (typeof value === 'string' && value.includes('*')) {
    const root = siteRoot(value);
    if (root) return { entry: value, root };
    const shaped = /^(https?):\/\/\*\.([^/?#*\s:]+)$/.exec(value);
    if (shaped?.[1] === 'http') return { error: `Domain roots are https only: ${text} (write https://*.${shaped[2]})` };
    if (shaped && /^[a-z0-9.-]+$/.test(shaped[2]) && isSiteSuffix(shaped[2])) {
      return { error: `Not a registrable domain: ${text} (${shaped[2]} is a public suffix, a shared hosting domain or under an `
        + 'unknown top-level domain; name one site, like https://*.example.co.uk, or use exact origins)' };
    }
    return { error: `Not a domain root: ${text} (write https://*.example.com in lower case, with no path or port)` };
  }
  const origin = exactOrigin(value);
  return origin ? { entry: origin } : { error: `Not an exact http(s) origin without a path: ${text}` };
}

/** The domain roots among `entries`. */
export function siteRoots(entries) {
  return Array.isArray(entries) ? entries.map(siteRoot).filter(Boolean) : [];
}

/** The Chrome host permission patterns for the domain roots among `entries` (empty without one). */
export function sitePatterns(entries) {
  return siteRoots(entries).map(sitePattern);
}

function urlOrigin(url) {
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

/** True when the URL's origin is covered by `entries` (an unparsable URL never is). */
export function urlCovered(url, entries) {
  const origin = urlOrigin(url);
  return origin !== null && originCovered(origin, entries);
}

/**
 * True when a link or navigation from `fromUrl` to `toUrl` stays on the approved site: the destination is covered and
 * is either the same origin or under a domain root that also covers the origin it leaves.
 */
export function sameSite(fromUrl, toUrl, entries) {
  const from = urlOrigin(fromUrl);
  const to = urlOrigin(toUrl);
  if (!from || !to || !originCovered(to, entries)) return false;
  if (from === to) return true;
  const fromHost = siteHost(from);
  const toHost = siteHost(to);
  return Boolean(fromHost && toHost) && siteRoots(entries).some(root => hostInSite(fromHost, root) && hostInSite(toHost, root));
}

/**
 * True when the request `entries` already cover the asked `entry`: an exact origin covered by them, or a domain root
 * listed there or inside a broader listed root.
 */
export function entryCovered(entry, entries) {
  const root = siteRoot(entry);
  if (!root) return originCovered(entry, entries);
  return siteRoots(entries).some(listed => hostInSite(root, listed));
}

/**
 * The origins a lease covers. `domain` scope (the user approved the domain roots and Chrome granted the host
 * permission) keeps the request's entries as they are; `origin` scope keeps its exact entries plus the tab's origin, so
 * a root the user did not approve covers nothing beyond the page the tab was on.
 */
export function leaseOrigins(entries, tabOrigin, scope) {
  const list = Array.isArray(entries) ? entries : [];
  if (scope === 'domain' && siteRoots(list).length) return [...list];
  const exact = list.filter(entry => !siteRoot(entry));
  if (typeof tabOrigin === 'string' && !exact.includes(tabOrigin) && originCovered(tabOrigin, list)) exact.push(tabOrigin);
  return exact;
}

/**
 * The registrable domain of a host as this list knows it (the shortest ending that is a valid root), or null for an
 * IP address, a single label or a known public suffix.
 */
export function registrableDomain(host) {
  if (typeof host !== 'string' || !/^[a-z0-9.-]+$/.test(host) || host.endsWith('.')) return null;
  const labels = host.split('.');
  for (let i = labels.length - 2; i >= 0; i--) {
    const candidate = labels.slice(i).join('.');
    if (siteRoot(`https://*.${candidate}`)) return candidate;
  }
  return null;
}

/**
 * The domain-root entry that would cover `origin` (an https origin on the default port), e.g.
 * "https://*.mozilla.org" for https://developer.mozilla.org, or null.
 */
export function siteEntryFor(origin) {
  const root = registrableDomain(siteHost(origin));
  return root ? `https://*.${root}` : null;
}

/** Plain words for an entry: "all of example.com" for a domain root, the origin itself for an exact one. */
export function describeEntry(entry) {
  const root = siteRoot(entry);
  return root ? `all of ${root}` : String(entry);
}

// A navigation verb right before the URL: "Open", "go to", "navigate to", "load", "visit", "browse to", optionally
// with "the page", "the URL" or "this URL" (and "at") in between. Anything else ("compare with https://...") is not
// a hop.
const URL_HOP_VERB =
  /\b(?:open|go\s+to|navigate\s+to|load|visit|browse\s+to)\s+(?:(?:the|this)\s+(?:page|url|link)\s+)?(?:at\s+)?[<("'`“]?$/i;
export const URL_IN_TEXT = /https?:\/\/[^\s<>"'`”]+/gi;

/** A URL_IN_TEXT match without its sentence punctuation; a closing bracket stays only when the URL opened it ("/wiki/Tab_(interface)"). */
export function trimNamedUrl(raw) {
  let url = String(raw);
  for (;;) {
    const next = url.replace(/[.,;:!?\]]+$/, '');
    const open = next.split('(').length;
    const close = next.split(')').length;
    const trimmed = next.endsWith(')') && close > open ? next.slice(0, -1) : next;
    if (trimmed === url) return url;
    url = trimmed;
  }
}
// A URL whose path or short query words sign out, unsubscribe or submit is never hopped to (guardrail classes too).
export const URL_HOP_REFUSED = /\b(?:log ?out|sign ?out|unsubscribe|opt ?out|submit)\b/i;

// A negation right before the verb ("do not open", "never visit", "don't go to"): the URL is one not to open.
const URL_HOP_NEGATED = /\b(?:not|never|don[\u2019']?t|without|avoid|skip)\s+$/i;

/**
 * The URLs `instruction` names right after a navigation verb (not a negated one), in order, trailing punctuation
 * dropped. With `template` (the host's own text, before a list fills its placeholders) only the URLs the template
 * names as well: a URL a placeholder wrote in is page text, and page text never picks where the tab goes.
 */
export function namedUrls(instruction, template) {
  const text = String(instruction ?? '');
  const trusted = template === undefined ? null : new Set(namedUrls(template));
  const out = [];
  for (const match of text.matchAll(URL_IN_TEXT)) {
    const before = text.slice(Math.max(0, match.index - 60), match.index);
    const verb = URL_HOP_VERB.exec(before);
    if (!verb || URL_HOP_NEGATED.test(before.slice(0, verb.index))) continue;
    const url = trimNamedUrl(match[0]);
    try {
      const href = new URL(url).href;
      if (!trusted || trusted.has(href)) out.push(href);
    } catch {
      // Not a URL after all.
    }
  }
  return out;
}

/**
 * The page a tab request asks the extension to open on approval, from what the host wrote: the first `allowedUrls`
 * entry on `origins`, else the first URL an instruction names after a navigation verb (namedUrls) on `origins`; never
 * a sign-out or submit URL. Undefined when there is none (the daemon then opens the first origin's root).
 */
export function requestStartUrl(origins, allowedUrls, instructions) {
  const candidates = [...(Array.isArray(allowedUrls) ? allowedUrls : [])];
  for (const text of instructions) {
    // A URL a {{answer:N}} placeholder writes in comes from page text: only what the host wrote counts.
    if (typeof text === 'string') candidates.push(...namedUrls(text.replace(/\S*\{\{answer:\d+\}\}\S*/g, ' ')));
  }
  return candidates.find(url => {
    if (typeof url !== 'string' || url.length > 2048 || !/^https?:\/\//i.test(url) || !urlCovered(url, origins)) {
      return false;
    }
    const { pathname, search } = new URL(url);
    return !URL_HOP_REFUSED.test(`${pathname} ${search}`.replace(/[/?&=_.+-]+/g, ' '));
  });
}

