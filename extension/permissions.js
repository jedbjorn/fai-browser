// Per-request call budget (Advanced): what an agent may spend on one tab request (calls, run minutes) before the MCP
// server stops it. Stored as `chrome.storage.local.budget` {maxCalls, maxMs}; absent means the daemon's own default
// applies (config.json `budget`, else 50 calls and 20 minutes). The worker reports it in its hello and on every
// change; the agent cannot change it. The bounds are src/settings.js
// BUDGET_LIMITS (test/extension-permissions.test.js checks the two agree).

export const BUDGET_LIMITS = Object.freeze({
  maxCalls: Object.freeze({ min: 1, max: 10_000 }),
  maxMs: Object.freeze({ min: 1000, max: 14_400_000 }),
});
const MINUTE_MS = 60_000;
/** The minutes the popup accepts: whole minutes within BUDGET_LIMITS.maxMs. */
export const BUDGET_MINUTES = Object.freeze({ min: 1, max: BUDGET_LIMITS.maxMs.max / MINUTE_MS });

/** `chrome.storage.local.budget` validated: `{ maxCalls, maxMs }` within the bounds, else null (not set). */
export function normalizeBudget(stored) {
  if (!stored || typeof stored !== 'object') return null;
  const { maxCalls, maxMs } = stored;
  if (!Number.isInteger(maxCalls) || maxCalls < BUDGET_LIMITS.maxCalls.min || maxCalls > BUDGET_LIMITS.maxCalls.max) return null;
  if (!Number.isInteger(maxMs) || maxMs < BUDGET_LIMITS.maxMs.min || maxMs > BUDGET_LIMITS.maxMs.max) return null;
  return { maxCalls, maxMs };
}

/**
 * The popup's two fields to a budget: `{ budget }` (null when both are empty: the setting is removed), or `{ error }`
 * in plain words when a value is not a whole number within the bounds.
 */
export function budgetFromFields({ calls, minutes }) {
  const callsText = String(calls ?? '').trim();
  const minutesText = String(minutes ?? '').trim();
  if (!callsText && !minutesText) return { budget: null };
  const whole = text => (/^\d+$/.test(text) ? Number(text) : NaN);
  const maxCalls = whole(callsText);
  if (callsText && !(maxCalls >= BUDGET_LIMITS.maxCalls.min && maxCalls <= BUDGET_LIMITS.maxCalls.max)) {
    return { error: `Calls must be a whole number from ${BUDGET_LIMITS.maxCalls.min} to ${BUDGET_LIMITS.maxCalls.max}.` };
  }
  const minutesValue = whole(minutesText);
  if (minutesText && !(minutesValue >= BUDGET_MINUTES.min && minutesValue <= BUDGET_MINUTES.max)) {
    return { error: `Minutes must be a whole number from ${BUDGET_MINUTES.min} to ${BUDGET_MINUTES.max}.` };
  }
  // One field filled (the user is still typing the other): nothing is saved yet.
  if (!callsText || !minutesText) return { error: 'Fill in both calls and minutes, or leave both empty.' };
  return { budget: { maxCalls, maxMs: minutesValue * MINUTE_MS } };
}

/** "50 calls, 20 min" for a budget; the minutes rounded to one decimal when not whole. */
export function describeBudget(budget) {
  const clean = normalizeBudget(budget);
  if (!clean) return '';
  const minutes = Math.round(clean.maxMs / MINUTE_MS * 10) / 10;
  return `${clean.maxCalls} call${clean.maxCalls === 1 ? '' : 's'}, ${minutes} min`;
}

/** `chrome.storage.local.domainMemory` validated: `{ remember }`, off unless explicitly true. */
export function normalizeDomainMemory(stored) {
  return { remember: stored?.remember === true };
}

/**
 * `chrome.storage.local.rememberedSites` validated: `[{ root, until }]` with a valid domain root, an expiry in the
 * future and at most REMEMBER_MS away, no duplicates, at most MAX_REMEMBERED_SITES.
 */
export function normalizeRememberedSites(stored, now = Date.now()) {
  const out = [];
  for (const item of Array.isArray(stored) ? stored : []) {
    const until = Number(item?.until);
    if (!(until > now) || until > now + REMEMBER_MS) continue;
    const root = typeof item?.root === 'string' ? item.root : '';
    if (siteRoot(`https://*.${root}`) !== root) continue;
    if (out.some(entry => entry.root === root)) continue;
    out.push({ root, until });
    if (out.length >= MAX_REMEMBERED_SITES) break;
  }
  return out;
}

/**
 * The line under "All of <root>" about Chrome's site-access prompt, given which of the roots' patterns Chrome already
 * holds (`held`), which roots are remembered (`remembered`, [{ root, until }]) and the level chosen on the card:
 * `{ kind, text }` with kind `prompt` (Chrome will ask), `remembered` (no prompt, remembered for this level),
 * `again` (remembered for Read-only/Reversible only: the popup ends it as soon as the card shows this, before any
 * click, so Chrome asks again) or `granted`
 * (Chrome already allows the extension there, from its site-access setting: no prompt will appear).
 */
export function promptNote(choice, { held = [], remembered = [], level = 'read-only', clock = ms => new Date(ms).toISOString() } = {}) {
  const heldAll = choice.patterns.every(pattern => held.includes(pattern));
  const rememberedHere = remembered.filter(site => choice.roots.includes(site.root));
  const rememberedAll = choice.roots.every(root => rememberedHere.some(site => site.root === root));
  if (!heldAll) return { kind: 'prompt', text: 'Chrome asks you to allow site access.' };
  if (rememberedAll && REMEMBER_LEVELS.includes(level)) {
    return { kind: 'remembered', text: `Remembered until ${clock(Math.min(...rememberedHere.map(site => site.until)))}: no Chrome prompt.` };
  }
  if (rememberedAll) {
    return { kind: 'again', text: `Remembered for lower levels only: ending it so Chrome asks again at ${LEVEL_TEXT[level]?.name ?? level}.` };
  }
  return { kind: 'granted', text: 'Chrome already allows this extension on these sites (its site access setting): no prompt will appear.' };
}
